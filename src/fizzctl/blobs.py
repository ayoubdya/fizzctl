"""Baked firmware bytes, inlined as hex so the package ships no binary files.

All constants come from USB captures of the OEM software:
  * CONST_MODE / CONST_CANVAS / CONST_ROUTING / CONST_EXEC — the
    four constant 1032-byte frames of the Restore sequence.
  * FW_TEMPLATE — the 5-frame effect template: shared MODE and ROUTING,
    a distinct CANVAS, and five byte overrides of CONST_EXEC.
  * RGB_EXEC / RGB_SEC — the whole-board solid-color variant.
"""


def _patch(base: bytes, diffs: dict[int, int]) -> bytes:
    """Copy `base`, overriding a handful of byte offsets."""
    b = bytearray(base)
    for off, val in diffs.items():
        b[off] = val
    return bytes(b)


